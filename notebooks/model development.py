import rasterio
from rasterio.warp import calculate_default_transform, reproject, Resampling

input_dem = "/content/nasadem/output_be.tif"
projected_dem = "/content/sri_lanka_dem_utm.tif"

dst_crs = "EPSG:32644"

with rasterio.open(input_dem) as src:

    transform, width, height = calculate_default_transform(
        src.crs,
        dst_crs,
        src.width,
        src.height,
        *src.bounds
    )

    kwargs = src.meta.copy()

    kwargs.update({
        "crs": dst_crs,
        "transform": transform,
        "width": width,
        "height": height,
        "nodata": src.nodata
    })

    with rasterio.open(projected_dem, "w", **kwargs) as dst:

        reproject(
            source=rasterio.band(src, 1),
            destination=rasterio.band(dst, 1),
            src_transform=src.transform,
            src_crs=src.crs,
            dst_transform=transform,
            dst_crs=dst_crs,
            resampling=Resampling.bilinear
        )

print("DEM projected successfully!")

with rasterio.open(projected_dem) as src:
    print("New CRS:", src.crs)
    print("Resolution:", src.res)
    print("Width:", src.width)
    print("Height:", src.height)

import numpy as np
import rasterio

with rasterio.open(projected_dem) as src:

    dem = src.read(1).astype("float32")

    nodata = src.nodata

    if nodata is not None:
        dem[dem == nodata] = np.nan

    x_resolution = src.res[0]
    y_resolution = abs(src.res[1])

    profile = src.profile.copy()

print("X resolution:", x_resolution, "m")
print("Y resolution:", y_resolution, "m")

dy, dx = np.gradient(
    dem,
    y_resolution,
    x_resolution
)

slope_radians = np.arctan(
    np.sqrt(dx**2 + dy**2)
)

slope_degrees = np.degrees(slope_radians)

print("Minimum slope:", np.nanmin(slope_degrees))
print("Maximum slope:", np.nanmax(slope_degrees))
print("Mean slope:", np.nanmean(slope_degrees))

