slope_path = "/content/sri_lanka_slope.tif"

terrain_results = []

with rasterio.open(dem_path) as dem_src, rasterio.open(slope_path) as slope_src:

    for _, row in districts_utm.iterrows():

        district_name = row["District"]
        geometry = [row.geometry]

        # ----- ELEVATION -----
        dem_crop, _ = mask(
            dem_src,
            geometry,
            crop=True,
            filled=False
        )

        elevation_values = dem_crop[0].compressed()

        # ----- SLOPE -----
        slope_crop, _ = mask(
            slope_src,
            geometry,
            crop=True,
            filled=False
        )

        slope_values = slope_crop[0].compressed()

        # Remove invalid values
        elevation_values = elevation_values[
            np.isfinite(elevation_values)
        ]

        slope_values = slope_values[
            np.isfinite(slope_values)
        ]

        terrain_results.append({
            "District": district_name,
            "Mean_Elevation_m": np.mean(elevation_values),
            "Median_Elevation_m": np.median(elevation_values),
            "Mean_Slope_deg": np.mean(slope_values),
            "Median_Slope_deg": np.median(slope_values)
        })

        print("Completed:", district_name)

print("\nAll districts completed!")

